    static generateTreasure(level=COMMON, type=ALL, num=1) {
        let i = 0
        let items = []
        while (i < num) {
            items.push(this.magicItems[level][getRandInt(this.magicItems[level].length)]["item"])
            i ++
        }
        return items
    }
